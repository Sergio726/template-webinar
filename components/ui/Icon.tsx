import { createElement } from "react"
import * as icons from "lucide-react"
import type { LucideProps } from "lucide-react"

/**
 * Puente entre el config y lucide-react.
 *
 * El config guarda el nombre del icono como texto ("Calendar"), no el
 * componente: asi el objeto de configuracion sigue siendo datos planos y puede
 * cruzar el limite servidor/cliente sin problema.
 *
 * Si el nombre no existe se devuelve null en vez de romper la pagina: un icono
 * mal escrito no deberia tumbar una landing en produccion.
 */

type IconRegistry = Record<string, unknown>

function resolveIcon(name?: string | null) {
  if (!name) return null
  const candidate = (icons as IconRegistry)[name]
  return typeof candidate === "function"
    ? (candidate as React.ComponentType<LucideProps>)
    : null
}

export function Icon({
  name,
  className,
  ...props
}: { name?: string | null; className?: string } & LucideProps) {
  const component = resolveIcon(name)
  if (!component) return null
  // createElement en lugar de JSX: el componente se elige en tiempo de
  // ejecucion y no es una referencia estatica que React pueda seguir.
  return createElement(component, { className, "aria-hidden": true, ...props })
}

